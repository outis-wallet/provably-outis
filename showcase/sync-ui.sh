#!/bin/sh
# Regenerates the apps' UI (showcase/index.html, results.html, app.js, app.css) from the Outis
# Prover React app, outis/wallet/apps/prover: its native build, written here. Then commit the
# four files, naming the Outis commit (printed at the end). See docs/SHOWCASE.md.
#
# Usage: showcase/sync-ui.sh (needs pnpm). OUTIS=<path> points at the Outis checkout, default
# ../outis next to this repository. Builds whatever that checkout has: pull it first.
set -e
cd "$(dirname "$0")/.."
SHOWCASE=$(pwd)/showcase
OUTIS=${OUTIS:-../outis}
APP="$OUTIS/wallet/apps/prover"

if [ ! -f "$APP/package.json" ]; then
  echo "No wallet/apps/prover in $OUTIS. Pull the Outis checkout, or set OUTIS=<path to it>." >&2
  exit 1
fi
command -v pnpm > /dev/null || { echo "pnpm is needed (corepack enable, or npm i -g pnpm)." >&2; exit 1; }

# The commit the UI comes from, +dirty if the app or the UI package it uses has changes.
commit=$(git -C "$OUTIS" rev-parse --short=10 HEAD)
if [ -n "$(git -C "$OUTIS" status --porcelain -- wallet/apps/prover wallet/packages/ui)" ]; then
  commit="$commit+dirty"
  echo "Note: $OUTIS has uncommitted changes in wallet/apps/prover or wallet/packages/ui." >&2
fi

[ -d "$APP/node_modules" ] || (cd "$OUTIS/wallet" && pnpm install --frozen-lockfile --filter "@outis/prover...")
# The build's log only if it fails (its sizes are from before the font swap, so they'd mislead).
log=$(mktemp)
(cd "$APP" && NATIVE_OUT="$SHOWCASE" pnpm --silent build:native > "$log" 2>&1) || { cat "$log" >&2; rm -f "$log"; exit 1; }
rm -f "$log"

for file in index.html results.html app.js app.css; do
  head -c 200 "$SHOWCASE/$file" | grep -q "Generated by outis/wallet/apps/prover" || {
    echo "showcase/$file isn't the generated one." >&2
    exit 1
  }
done

if git diff --quiet -- showcase/index.html showcase/results.html showcase/app.js showcase/app.css; then
  echo "showcase/ is already the UI of outis $commit."
else
  git diff --stat -- showcase/index.html showcase/results.html showcase/app.js showcase/app.css
  echo "Commit it with: git commit -m \"showcase: UI from outis $commit\" showcase/index.html showcase/results.html showcase/app.js showcase/app.css"
fi
